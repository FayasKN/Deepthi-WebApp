// src/data/numbers_6to100.ts
// Numbers 6–100 — import and spread into numbersData in modules.ts
// For numbers > 10 we use grouped objects (e.g. "countable groups" instead of individual dots)

export interface NumberItem {
  id: string;
  numeral: number;
  word_en: string;
  word_ml: string;
  dots: number;          // for ≤10; for >10 use groups display
  audio_en: string;
  audio_ml: string;
  quiz: {
    question_en: string;
    question_ml: string;
    options: number[];
    answer: number;
  };
}

// ─── Helper to build a number entry quickly ───────────────────────────────────
function num(
  n: number,
  word_en: string,
  word_ml: string,
  quizOptions: number[]
): NumberItem {
  return {
    id: String(n),
    numeral: n,
    word_en,
    word_ml,
    dots: n <= 20 ? n : 0,   // dots only rendered for ≤ 20; >20 shows numeral groups
    audio_en: `/audio/en/${n}.mp3`,
    audio_ml: `/audio/ml/${n}.mp3`,
    quiz: {
      question_en: `Which number is ${n}?`,
      question_ml: `ഏതാണ് ${n}?`,
      options: quizOptions,
      answer: n,
    },
  };
}

